extern TIM_HandleTypeDef htim2;
extern TIM_HandleTypeDef htim4;
extern void Position_Control_Loop(void);

/**
  * @brief This function handles TIM2 global interrupt (Z相输入捕获).
  */
void TIM2_IRQHandler(void)
{
    HAL_TIM_IRQHandler(&htim2);
}

volatile uint32_t z_pulse_count = 0;
int32_t z_last_pos = 0;  // homing.c/Z_FINE阶段会修改此值

/**
  * @brief  TIM2输入捕获回调 —— Z相脉冲, ICFilter=15硬件滤波 + 位置校验
  *         要求两次Z脉冲至少间隔1800计数(1.8mm), 对应2.0mm极距
  */
void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2 && htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1)
    {
        int32_t pos = Mag_Get_Pos();
        int32_t dist = pos - z_last_pos;
        if (dist < 0) dist = -dist;  // abs
        if (dist >= 1800)  // 至少走了1.8mm才接受
        {
            z_pulse_count++;
            z_last_pos = pos;
        }
    }
}

/**
  * @brief This function handles TIM4 global interrupt.
  */
void TIM4_IRQHandler(void)
{
  if (__HAL_TIM_GET_FLAG(&htim4, TIM_FLAG_UPDATE) != RESET)
  {
    if (__HAL_TIM_GET_IT_SOURCE(&htim4, TIM_IT_UPDATE) != RESET)
    {
      __HAL_TIM_CLEAR_IT(&htim4, TIM_IT_UPDATE);
      Position_Control_Loop();
    }
  }
}
